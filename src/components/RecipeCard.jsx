import { Link } from 'react-router-dom';
import { Check, CheckCircle, ShieldCheck, Sparkle, Timer, UsersThree, Warning, WarningCircle } from '@phosphor-icons/react';

const NUTRITION_SOURCES = {
  calculated: 'Calculated from our nutrition dataset.',
  partly_estimated: 'Calculated from our nutrition dataset, with AI estimates for some ingredients.',
  ai_estimated: 'AI-estimated values, not checked against our nutrition dataset.',
};

export default function RecipeCard({ recipe, accepted = {}, onAccept, children }) {
  const { alignment, substitutions, supplements } = recipe;
  const { kcal, protein, carbs, fat } = recipe.nutrition;
  const badges = [recipe.meal, recipe.cuisine, recipe.difficulty, recipe.budget && recipe.budget !== 'Any' ? `${recipe.budget} budget` : null]
    .filter((b) => b && b !== 'Any');

  return (
    <article className="recipe" aria-labelledby="recipe-title">
      {recipe.source === 'sample' ? (
        <p className="sample-tag">Sample recipe, not generated by AI</p>
      ) : (
        <p className="mock-kicker"><Sparkle size={14} weight="fill" aria-hidden /> Written by AI, please check it before cooking</p>
      )}
      <h2 id="recipe-title" className="recipe-title">{recipe.title}</h2>
      <p className="recipe-desc">{recipe.description}</p>
      <ul className="meta-list">
        <li><Timer size={16} aria-hidden /> {recipe.minutes} min</li>
        <li><UsersThree size={16} aria-hidden /> Serves {recipe.servings}</li>
      </ul>
      {badges.length > 0 && (
        <ul className="chip-list recipe-badges" aria-label="Filters">
          {badges.map((badge) => <li key={badge} className="chip">{badge}</li>)}
        </ul>
      )}

      {recipe.constraint_warning && (
        <div className="care-note recipe-note" role="note"><p>{recipe.constraint_warning}</p></div>
      )}

      <p className="safety-pass">
        <ShieldCheck size={20} weight="fill" aria-hidden />
        {recipe.allergiesChecked?.length
          ? `Allergen check passed: no ${recipe.allergiesChecked.join(', ')} found in the ingredients.`
          : 'No allergies listed, so nothing was checked.'}
        {' '}Always check labels yourself.
      </p>

      <section aria-labelledby="nutrition-title" className="recipe-block">
        <h3 id="nutrition-title" className="dash-h2">Nutrition per serving</h3>
        <dl className="target-list target-list-4">
          <div><dt>Calories</dt><dd>{kcal} <small>kcal</small></dd></div>
          <div><dt>Protein</dt><dd>{protein} <small>g</small></dd></div>
          <div><dt>Carbs</dt><dd>{carbs} <small>g</small></dd></div>
          <div><dt>Fat</dt><dd>{fat} <small>g</small></dd></div>
        </dl>
        <p className="field-hint">{NUTRITION_SOURCES[recipe.nutritionSource]}</p>
        {recipe.nutritionWarning && (
          <p className="estimate-warning" role="note">
            <Warning size={16} weight="fill" aria-hidden /> These numbers look unusual, so treat them with caution.
          </p>
        )}
      </section>

      <section aria-labelledby="alignment-title" className="recipe-block">
        <h3 id="alignment-title" className="dash-h2">Goal alignment</h3>
        {alignment ? (
          <ul className="alignment">
            {alignment.map((item) => (
              <li key={item.key} className={item.pass ? 'is-pass' : 'is-warn'}>
                {item.pass ? <CheckCircle size={20} weight="fill" aria-hidden /> : <WarningCircle size={20} weight="fill" aria-hidden />}
                <span><b>{item.label}: {item.pass ? 'On target' : 'Warning'}.</b> {item.text}</span>
              </li>
            ))}
          </ul>
        ) : (
          <p><Link to="/dashboard/profile" className="inline-link">Complete your profile</Link> to see how recipes fit your goals.</p>
        )}
      </section>

      <div className="recipe-columns">
        <section aria-labelledby="ing-title">
          <h3 id="ing-title" className="dash-h2">Ingredients</h3>
          <ul className="recipe-ingredients">
            {recipe.ingredients.map((i) => (
              <li key={i.name}>
                <span>{i.amount} {i.name}</span>
                {i.missing && <b className="missing-tag">Missing</b>}
              </li>
            ))}
          </ul>
        </section>
        <section aria-labelledby="steps-title">
          <h3 id="steps-title" className="dash-h2">Method</h3>
          <ol className="recipe-steps">
            {recipe.steps.map((step) => <li key={step}>{step}</li>)}
          </ol>
        </section>
      </div>

      {substitutions.length > 0 && (
        <section aria-labelledby="subs-title" className="recipe-block">
          <h3 id="subs-title" className="dash-h2">Smart substitutions</h3>
          <ul className="subs">
            {substitutions.map(({ ingredient, options }) => (
              <li key={ingredient}>
                <p>Instead of <b>{ingredient}</b>:</p>
                <div className="chip-list">
                  {options.map((option) => {
                    const on = accepted[ingredient] === option.name;
                    return onAccept ? (
                      <button
                        key={option.name}
                        type="button"
                        className={`chip chip-btn${on ? ' chip-on' : ''}`}
                        aria-pressed={on}
                        onClick={() => onAccept(ingredient, on ? null : option.name)}
                      >
                        {on && <Check size={14} weight="bold" aria-hidden />}
                        {option.name}, {option.reason}
                      </button>
                    ) : (
                      <span key={option.name} className="chip">{option.name}, {option.reason}</span>
                    );
                  })}
                </div>
              </li>
            ))}
          </ul>
        </section>
      )}

      <p className="recipe-why"><b>Why this suits you:</b> {recipe.why_it_fits}</p>
      {recipe.label_checks?.length > 0 && (
        <p className="recipe-why"><b>Check these labels:</b> {recipe.label_checks.join(', ')}</p>
      )}

      {supplements.length > 0 && (
        <section aria-labelledby="supp-title" className="supplement-box">
          <h3 id="supp-title" className="dash-h2">Optional supplement notes</h3>
          <ul>
            {supplements.map((s) => <li key={s.title}><b>{s.title}:</b> {s.text}</li>)}
          </ul>
          <p className="disclaimer"><Warning size={16} weight="fill" aria-hidden /> {supplements[0].disclaimer}</p>
        </section>
      )}

      <p className="recipe-disclaimer">
        AI can make mistakes. If you have an allergy, check every ingredient and label yourself.
        This isn&apos;t medical or dietary advice.
      </p>
      {children}
    </article>
  );
}
